#!/usr/bin/env bash
# Render a release-pinned Homebrew formula (`mattyx.rb`) from the `.sha256`
# sidecars produced by `.github/workflows/release.yml` (issue #141).
#
# Usage:
#   scripts/render-homebrew-formula.sh <version> <dist_dir> [<output_file>]
set -euo pipefail

if [ "$#" -lt 2 ] || [ "$#" -gt 3 ]; then
  echo "usage: $0 <version> <dist_dir> [<output_file>]" >&2
  exit 2
fi

VERSION="${1#v}"
DIST_DIR="$2"
OUTPUT_FILE="${3:-}"

read_sha256() {
  local sidecar="${DIST_DIR%/}/$1.sha256"
  if [ ! -f "$sidecar" ]; then
    echo "render-homebrew-formula.sh: missing sidecar: $sidecar" >&2
    return 1
  fi
  local sha
  sha="$(awk 'NF {print tolower($1); exit}' "$sidecar" | tr -d '\r')"
  if ! printf '%s' "$sha" | grep -Eq '^[0-9a-f]{64}$'; then
    echo "render-homebrew-formula.sh: invalid sha256 in $sidecar: '$sha'" >&2
    return 1
  fi
  printf '%s' "$sha"
}

SHA_MACOS_AARCH64="$(read_sha256 "mtyx-macos-aarch64")"
SHA_MACOS_X86_64="$(read_sha256 "mtyx-macos-x86_64")"
SHA_LINUX_AARCH64="$(read_sha256 "mtyx-linux-aarch64")"
SHA_LINUX_X86_64="$(read_sha256 "mtyx-linux-x86_64")"

render() {
  cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/render-homebrew-formula.sh for mattyx v${VERSION}.
class Mattyx < Formula
  desc "Agent-aware terminal multiplexer backed by libghostty-vt"
  homepage "https://github.com/mathewclarkau/mattyx"
  version "${VERSION}"
  license "GPL-3.0-or-later"

  on_macos do
    on_arm do
      url "https://github.com/mathewclarkau/mattyx/releases/download/v#{version}/mtyx-macos-aarch64"
      sha256 "${SHA_MACOS_AARCH64}"
    end
    on_intel do
      url "https://github.com/mathewclarkau/mattyx/releases/download/v#{version}/mtyx-macos-x86_64"
      sha256 "${SHA_MACOS_X86_64}"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/mathewclarkau/mattyx/releases/download/v#{version}/mtyx-linux-aarch64"
      sha256 "${SHA_LINUX_AARCH64}"
    end
    on_intel do
      url "https://github.com/mathewclarkau/mattyx/releases/download/v#{version}/mtyx-linux-x86_64"
      sha256 "${SHA_LINUX_X86_64}"
    end
  end

  def install
    if OS.mac?
      bin.install(Hardware::CPU.arm? ? "mtyx-macos-aarch64" : "mtyx-macos-x86_64" => "mtyx")
    else
      bin.install(Hardware::CPU.arm? ? "mtyx-linux-aarch64" : "mtyx-linux-x86_64" => "mtyx")
    end
  end

  test do
    assert_equal "mtyx #{version}", shell_output("#{bin}/mtyx --version").strip
  end
end
EOF
}

if [ -n "$OUTPUT_FILE" ]; then
  render > "$OUTPUT_FILE"
  echo "wrote $OUTPUT_FILE"
else
  render
fi
